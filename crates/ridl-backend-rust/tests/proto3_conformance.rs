/// The Rust `prost` writes for the fixture's two packages, composed as
/// `pb::conformance` and `pb::parts` so that the `super::parts::` paths the
/// cross-package references take resolve.
#[allow(
    warnings,
    reason = "third-party generated code, checked in verbatim so that a \
              regeneration can be compared byte for byte; editing it to \
              satisfy a lint would make that comparison impossible"
)]
mod prost_oracle {
    include!("generated/proto3_conformance_prost.rs");
}

/// Regenerates the checked-in oracle and returns its source: the `.proto`
/// of both packages from the schema backend, compiled by `protox`, written
/// by `prost-build` with `btree_map(["."])` so a map's entries are in key
/// order, one file per package, composed into one module tree in package
/// order.
fn prost_oracle_source() -> String {
    let files = proto3::emitted_proto();
    let fds = proto3::compile_protos(&files).file_descriptor_set();
    let dir = tempfile::tempdir().expect("a temp dir is created");
    prost_build::Config::new()
        .btree_map(["."])
        .out_dir(dir.path())
        .compile_fds(fds)
        .expect("prost-build generates Rust from the emitted schema");
    let bodies: Vec<(String, String)> = files
        .iter()
        .map(|(name, _)| {
            let package = name.strip_suffix(".proto").expect("a .proto file name");
            let path = dir.path().join(format!("{package}.rs"));
            let text = std::fs::read_to_string(&path)
                .unwrap_or_else(|error| panic!("read {}: {error}", path.display()));
            (package.to_string(), text)
        })
        .collect();
    format!(
        "// Generated by prost-build from the .proto the schema backend emits for\n\
         // tests/fixtures/proto3_conformance.ridl and proto3_conformance_other.ridl.\n\
         // Regenerate with `RIDL_UPDATE_GENERATED=1 cargo test -p ridl-backend-rust\n\
         // --test proto3_conformance`.\n{}",
        proto3::compose_modules(&bodies)
    )
}

/// The checked-in oracle is what `prost-build` writes from the emitted
/// schema, byte for byte.
///
/// Without this the cases below would prove only that this codec agrees
/// with a file someone once pasted into the tree. `prost`, `prost-build`
/// and `protox` are pinned in the workspace manifest, so a version bump that
/// changes the generated oracle fails here rather than silently changing
/// what conformance means. `RIDL_UPDATE_GENERATED=1` writes the fresh output
/// instead of comparing, the same switch the FlatBuffers suite uses.
#[test]
fn the_checked_in_prost_code_is_what_prost_build_writes() {
    let fresh = prost_oracle_source();
    let path =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/generated/proto3_conformance_prost.rs");

    if std::env::var_os("RIDL_UPDATE_GENERATED").is_some() {
        std::fs::write(&path, &fresh)
            .unwrap_or_else(|error| panic!("write {}: {error}", path.display()));
        return;
    }

    let checked_in = std::fs::read_to_string(&path)
        .unwrap_or_else(|error| panic!("read {}: {error}", path.display()));
    assert_eq!(
        fresh, checked_in,
        "the checked-in prost oracle is stale; regenerate it with \
         RIDL_UPDATE_GENERATED=1 cargo test -p ridl-backend-rust --test \
         proto3_conformance"
    );
}

