//! Conformance of the proto3 codec against `prost`, and the structural drift
//! test between the codec's layout and the emitted `.proto` schema, as the
//! proto3 codec design note specifies them.
//!
//! proto3 fixes a canonical encoding — fields in number order, a field at
//! its default omitted, numerics packed — and `prost` writes it, so unlike
//! the FlatBuffers suite this one claims **byte equality** with the oracle
//! in both directions: the bytes this codec writes for a value are the
//! bytes `prost` writes for the same value, and the bytes `prost` writes are
//! verified and decoded here to the same value. One exception is listed by
//! name: a float at `-0.0`, which the protobuf reference implementations
//! write (they compare by bits) and `prost` omits (it compares by value);
//! this codec follows the reference implementations, so the sign of zero
//! survives its own round trip, and
//! [`minus_zero_differs_from_prost_as_designed`] states the difference as a
//! case rather than skipping it.
//!
//! The oracle is `prost` code generated from the `.proto` the schema backend
//! emits for `tests/fixtures/proto3_conformance.ridl` and its second package
//! `proto3_conformance_other.ridl`, compiled by `protox` and written by
//! `prost-build`, **checked in** under `tests/generated/` with no `build.rs`
//! and no `protoc`. [`the_checked_in_prost_code_is_what_prost_build_writes`]
//! regenerates it and compares bytes. The fixture holds every shape the
//! codec carries, the value table below covers each of them, and
//! [`the_inventory_reaches_every_shape`] checks that the fixture's model
//! reaches every row of the wire mapping, so a shape cannot drop out of the
//! table unnoticed. [`proto3_layout_matches_the_emitted_schema`] requires
//! every message of the emitted schema to be laid out by the codec, over the
//! fixture and over every corpus package.
//!
//! The generated codec runs as a program, built once per test binary
//! (`support::proto3::Program`) and fed one request line per case, so the
//! suite's wall time is one `rustc` call and not one per case.

#[path = "support/proto3.rs"]
mod proto3;
#[path = "support/rustc.rs"]
mod rustc;

