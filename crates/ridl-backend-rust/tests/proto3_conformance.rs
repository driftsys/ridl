fn to_hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

fn from_hex(text: &str) -> Vec<u8> {
    assert!(
        text.len().is_multiple_of(2),
        "a transcript is a whole number of bytes, got {text:?}"
    );
    (0..text.len())
        .step_by(2)
        .map(|at| u8::from_str_radix(&text[at..at + 2], 16).expect("a hexadecimal byte"))
        .collect()
}

/// **Direction one.** The bytes this codec writes for every row are the
/// bytes `prost` writes for the same value, and `prost` decodes them to that
/// value.
///
/// The second half is what makes the first mean something: two writers that
/// agree on bytes whose reading `prost` disagrees with would be agreeing on
/// a different message.
#[test]
fn bytes_this_codec_writes_equal_prost_bytes() {
    let rows = rows();
    let lines: Vec<String> = rows
        .iter()
        .map(|row| format!("{} encode-named {}", row.message, row.name))
        .collect();
    let answers = program().run(&lines);
    let mut non_empty = 0usize;
    for (row, answer) in rows.iter().zip(&answers) {
        let ours = from_hex(answer);
        let theirs = row.prost.encode();
        assert_eq!(
            to_hex(&ours),
            to_hex(&theirs),
            "{}/{}: the bytes this codec writes must be the bytes prost writes",
            row.message,
            row.name
        );
        let decoded = row.prost.decode_debug(&ours).unwrap_or_else(|error| {
            panic!(
                "{}/{}: prost reads the bytes: {error}",
                row.message, row.name
            )
        });
        assert_eq!(
            decoded,
            row.prost.debug(),
            "{}/{}: prost must read the value this codec encoded",
            row.message,
            row.name
        );
        non_empty += usize::from(!ours.is_empty());
    }
    assert!(non_empty > rows.len() / 2, "most rows encode to something");
}

/// **Direction two.** The bytes `prost` writes for every row are verified by
/// this codec, and decoded to the value of the row: the re-encoding of what
/// was read is what this codec writes for the row's own value, which
/// [`bytes_this_codec_writes_equal_prost_bytes`] has shown to be `prost`'s
/// bytes.
#[test]
fn prost_bytes_decode_here() {
    let rows = rows();
    let mut lines: Vec<String> = Vec::new();
    for row in &rows {
        let theirs = to_hex(&row.prost.encode());
        lines.push(format!("{} verify {theirs}", row.message));
        lines.push(format!("{} decode-encode {theirs}", row.message));
        lines.push(format!("{} encode-named {}", row.message, row.name));
    }
    let answers = program().run(&lines);
    for (row, answer) in rows.iter().zip(answers.chunks(3)) {
        let [verdict, re_encoded, ours] = answer else {
            panic!("three answers per row");
        };
        assert_eq!(
            verdict, "ok",
            "{}/{}: this codec must verify the bytes prost writes",
            row.message, row.name
        );
        assert_eq!(
            re_encoded, ours,
            "{}/{}: the value read from prost's bytes must be the row's value",
            row.message, row.name
        );
    }
}

/// **The one listed exception to byte equality.** A `double` at `-0.0` is
/// written by this codec, `11` then the eight bytes of `-0.0`, because the
/// protobuf reference implementations compare a float by its bits and write
/// it; `prost` compares by value and writes nothing. `prost` reads the
/// written `-0.0` correctly, with its sign, so a value this codec sends
/// arrives intact; a `-0.0` sent through `prost` arrives as `+0.0`, which the
/// last assertion records.
#[test]
fn minus_zero_differs_from_prost_as_designed() {
    use prost::Message as _;
    use prost_oracle::pb::conformance as oracle;
    let minus_zero = oracle::Signs {
        ignored: 0,
        value: -0.0,
    };
    let theirs = Oracle::encode(&minus_zero);
    assert!(
        theirs.is_empty(),
        "prost omits -0.0; if this changes, the exception can be retired"
    );
    let answers = program().run(&[
        "Signs encode-named minus_zero".to_string(),
        format!("Signs decode-encode {}", to_hex(&theirs)),
    ]);
    assert_eq!(
        answers[0], "110000000000000080",
        "this codec writes -0.0, as the reference implementations do"
    );
    let read_back = oracle::Signs::decode(from_hex(&answers[0]).as_slice())
        .expect("prost reads the written -0.0");
    assert_eq!(read_back.value, 0.0);
    assert!(
        read_back.value.is_sign_negative(),
        "prost reads the sign this codec wrote"
    );
    assert_eq!(
        answers[1], "",
        "prost's bytes for -0.0 read here as +0.0, which is the empty message: the sign is \
         lost on that path, by prost's choice"
    );
}

/// Every message the codec emits, in both packages, is dispatched by the
/// program, and every one whose generated type has a `Default` value
/// encodes it to bytes that verify and re-encode to the same bytes. The
/// three without one (`Code` and `Key`, whose length excludes the empty
/// string, and `Lengths`, which holds `Code`) have no derivable init value
/// (TYPL-115).
#[test]
fn every_emitted_message_default_round_trips() {
    let program = program();
    let messages = program.messages();
    assert!(
        messages.len() >= 20,
        "the fixture emits many messages: {messages:?}"
    );
    for required in [
        "Scalars",
        "Axle",
        "Wheel",
        "GradeBox",
        "TorqueBox",
        "WideFlagsBox",
    ] {
        assert!(
            messages.contains(&required),
            "`{required}` is emitted: {messages:?}"
        );
    }
    let with_default = program.messages_with_default();
    let without: Vec<&str> = messages
        .iter()
        .copied()
        .filter(|message| !with_default.contains(message))
        .collect();
    assert_eq!(without, ["CodeBox", "KeyBox", "Lengths"]);
    let lines: Vec<String> = with_default
        .iter()
        .map(|message| format!("{message} encode-default"))
        .collect();
    let defaults = program.run(&lines);
    let lines: Vec<String> = with_default
        .iter()
        .zip(&defaults)
        .map(|(message, bytes)| format!("{message} decode-encode {bytes}"))
        .collect();
    let again = program.run(&lines);
    for ((message, first), second) in with_default.iter().zip(&defaults).zip(&again) {
        assert_eq!(
            first, second,
            "`{message}`: the default value's encoding round-trips"
        );
    }
}
