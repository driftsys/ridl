/// How a message's fields are spelled for the comparison: the number, the
/// scalar as the `.proto` spells it or the message or enum name (bare for
/// one of the same package, `pkg.Name` for a foreign one, which is how the
/// codec's layout spells both), and the label.
type Fields = Vec<(u32, String, Proto3Label)>;

/// The fields of one descriptor message, in number order, in the spelling of
/// [`Fields`].
fn descriptor_fields(message: &protox::prost_reflect::MessageDescriptor) -> Fields {
    let package = message.package_name();
    let mut fields: Fields = message
        .fields()
        .map(|field| {
            let ty = match field.kind() {
                Kind::Double => "double".to_string(),
                Kind::Float => "float".to_string(),
                Kind::Int32 => "int32".to_string(),
                Kind::Int64 => "int64".to_string(),
                Kind::Uint32 => "uint32".to_string(),
                Kind::Uint64 => "uint64".to_string(),
                Kind::Sint32 => "sint32".to_string(),
                Kind::Sint64 => "sint64".to_string(),
                Kind::Fixed32 => "fixed32".to_string(),
                Kind::Fixed64 => "fixed64".to_string(),
                Kind::Sfixed32 => "sfixed32".to_string(),
                Kind::Sfixed64 => "sfixed64".to_string(),
                Kind::Bool => "bool".to_string(),
                Kind::String => "string".to_string(),
                Kind::Bytes => "bytes".to_string(),
                Kind::Message(named) => local_or_qualified(package, named.full_name()),
                Kind::Enum(named) => local_or_qualified(package, named.full_name()),
            };
            let label = if field.is_list() || field.is_map() {
                Proto3Label::Repeated
            } else if field.field_descriptor_proto().proto3_optional() {
                Proto3Label::Optional
            } else {
                Proto3Label::Implicit
            };
            (field.number(), ty, label)
        })
        .collect();
    fields.sort_by_key(|field| field.0);
    fields
}

/// `full_name` with the package prefix removed when it is `package`'s.
fn local_or_qualified(package: &str, full_name: &str) -> String {
    full_name
        .strip_prefix(package)
        .and_then(|rest| rest.strip_prefix('.'))
        .filter(|rest| !rest.contains('.'))
        .map(str::to_string)
        .unwrap_or_else(|| full_name.to_string())
}

/// Compares the codec's layout of `package` with the descriptors of its
/// messages in `pool`: every emitted message exists in the schema with the
/// same fields, numbers, scalars and labels, and every top-level message of
/// the schema the codec does not emit is collected into `uncovered`. A map
/// entry is a nested message the schema synthesizes, so it is not a message
/// of the package.
fn compare(
    package: &v2::Package,
    others: &[&v2::Package],
    pool: &DescriptorPool,
    uncovered: &mut BTreeSet<String>,
    mismatches: &mut Vec<String>,
) {
    let layout: BTreeMap<String, Proto3MessageLayout> =
        ridl_backend_rust::proto3_layout(package, others)
            .unwrap_or_else(|error| panic!("{} lays out: {}", package.name, error.message))
            .into_iter()
            .map(|message| (message.name.clone(), message))
            .collect();
    let mut in_schema: BTreeSet<String> = BTreeSet::new();
    for message in pool.all_messages() {
        if message.package_name() != package.name
            || message.parent_message().is_some()
            || message.is_map_entry()
        {
            continue;
        }
        in_schema.insert(message.name().to_string());
        let Some(ours) = layout.get(message.name()) else {
            uncovered.insert(message.full_name().to_string());
            continue;
        };
        let theirs = descriptor_fields(&message);
        let mut fields = ours.fields.clone();
        fields.sort_by_key(|field| field.0);
        if fields != theirs {
            mismatches.push(format!(
                "{}: the codec lays out {fields:?}, the schema declares {theirs:?}",
                message.full_name()
            ));
        }
    }
    for name in layout.keys() {
        if !in_schema.contains(name) {
            mismatches.push(format!(
                "{}.{name}: the codec emits it, the schema has no such message",
                package.name
            ));
        }
    }
}

/// The layout the codec emits from equals the emitted `.proto` schema, field
/// by field, over the fixture and over every corpus package, so a
/// field-number, scalar or label disagreement between the two emitters fails
/// without running any generated code. The messages the codec does not emit
/// yet are exactly [`EXPECTED_UNCOVERED`] in the fixture, and as many as
/// [`CORPUS`] counts in each corpus entry.
#[test]
fn proto3_layout_matches_the_emitted_schema() {
    let mut mismatches: Vec<String> = Vec::new();

    // The fixture.
    let (main, others) = proto3::fixture();
    let mut packages = vec![main];
    packages.extend(others);
    let pool = proto3::compile_protos(&proto3::emit_protos(&packages, &[])).descriptor_pool();
    let mut uncovered: BTreeSet<String> = BTreeSet::new();
    for (at, package) in packages.iter().enumerate() {
        let others: Vec<&v2::Package> = packages
            .iter()
            .enumerate()
            .filter(|(other, _)| *other != at)
            .map(|(_, other)| other)
            .collect();
        compare(package, &others, &pool, &mut uncovered, &mut mismatches);
    }
    let expected: BTreeSet<String> = EXPECTED_UNCOVERED
        .iter()
        .map(|name| name.to_string())
        .collect();
    assert_eq!(
        uncovered, expected,
        "the messages the codec does not emit yet, in the fixture: a name listed but \
         emitted is stale, a name emitted nowhere but unlisted is new"
    );

    // The corpus.
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let std_ir = ridlc::std_ir();
    for (entry, expected_uncovered) in CORPUS {
        let packages = proto3::compile_workspace(&root.join(entry));
        assert!(!packages.is_empty(), "{entry} holds a package");
        let pool =
            proto3::compile_protos(&proto3::emit_protos(&packages, &[&std_ir])).descriptor_pool();
        let mut uncovered: BTreeSet<String> = BTreeSet::new();
        let mut covered = 0usize;
        for (at, package) in packages.iter().enumerate() {
            let mut others: Vec<&v2::Package> = packages
                .iter()
                .enumerate()
                .filter(|(other, _)| *other != at)
                .map(|(_, other)| other)
                .collect();
            others.push(&std_ir);
            compare(package, &others, &pool, &mut uncovered, &mut mismatches);
            covered += ridl_backend_rust::proto3_layout(package, &others)
                .expect("laid out above")
                .len();
        }
        assert!(covered > 0, "{entry}: the codec emits a message of it");
        assert_eq!(
            uncovered.len(),
            *expected_uncovered,
            "{entry}: the messages the codec does not emit yet ({covered} compared): \
             {uncovered:?}"
        );
    }

    assert!(
        mismatches.is_empty(),
        "the codec's layout and the emitted schema disagree:\n{}",
        mismatches.join("\n")
    );
}

