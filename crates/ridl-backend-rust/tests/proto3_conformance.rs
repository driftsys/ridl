/// `generate_pipeline` with proto3 succeeds for every package of the two
/// corpus entries whose every type has a proto3 bound — `examples/cabin` and
/// the veh-cluster corpus, whose interfaces induce argument and reply
/// messages — and every type gets a `Payload<Proto3>`. The ros2 corpus,
/// whose `RosString` has no length bound, is
/// [`the_ros2_corpus_is_refused_under_proto3`].
#[test]
fn the_corpus_generates_with_proto3() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let std_ir = ridlc::std_ir();
    let generate = |entry: &str| -> Vec<(String, Result<String, String>)> {
        let packages = proto3::compile_workspace(&root.join(entry));
        packages
            .iter()
            .enumerate()
            .map(|(at, package)| {
                let mut others: Vec<&v2::Package> = packages
                    .iter()
                    .enumerate()
                    .filter(|(other, _)| *other != at)
                    .map(|(_, other)| other)
                    .collect();
                others.push(&std_ir);
                let result = ridl_backend_rust::generate_pipeline(
                    package,
                    &[ridl_backend_rust::WireEncoding::Proto3],
                    false,
                    &others,
                )
                .map(|generated| generated.rust_source)
                .map_err(|error| error.message);
                (package.name.clone(), result)
            })
            .collect()
    };
    let cabin = generate("examples/cabin");
    let cluster = generate("crates/ridlc/tests/corpus/veh-cluster");
    for (entry, results) in [
        ("examples/cabin", &cabin),
        ("crates/ridlc/tests/corpus/veh-cluster", &cluster),
    ] {
        assert!(!results.is_empty(), "{entry} holds a package");
        for (name, result) in results {
            let source = result
                .as_ref()
                .unwrap_or_else(|error| panic!("{entry}: `{name}` generates with proto3: {error}"));
            assert!(
                source.contains("Payload<::ridl_rt::encoding::Proto3> for "),
                "{entry}: `{name}` carries a proto3 codec"
            );
        }
    }
    let (_, veh_cluster) = cluster
        .iter()
        .find(|(name, _)| name == "veh.cluster")
        .expect("the corpus declares `veh.cluster`");
    // Whitespace aside: the printer breaks a long `impl` line.
    let dense: String = veh_cluster
        .as_ref()
        .expect("generates")
        .chars()
        .filter(|c| !c.is_whitespace())
        .collect();
    for root in [
        "VehHvacCabinGetBoundsParams",
        "VehHvacCabinGetBoundsReply",
        "WheelDiagnosticsReadSpanReply",
    ] {
        assert!(
            dense.contains(&format!(
                "impl::ridl_rt::payload::Payload<::ridl_rt::encoding::Proto3>for{root}{{"
            )),
            "`{root}` is an induced interaction root with a `Payload<Proto3>`"
        );
    }
}

/// The ros2 corpus under `[Proto3]`: every package that declares a
/// `RosString` — a string with no length bound — is refused, with the
/// refusal naming that declaration and `NoBound`; `builtininterfaces`,
/// which declares no string, generates. Every package generates with no
/// encoding. The corpus pass leaves the workspace out ([`PROTO3_CORPUS`]).
/// The refusal at generation stands: the cap of such bounds that ADR-0030
/// decision 3 proposed was withdrawn (driftsys/ridl#996 holds the question).
#[test]
fn the_ros2_corpus_is_refused_under_proto3() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let std_ir = ridlc::std_ir();
    let packages = proto3::compile_workspace(&root.join("evals/corpus/ros2"));
    assert!(packages.len() > 1, "the ros2 corpus holds several packages");
    let mut refused: BTreeMap<String, String> = BTreeMap::new();
    let mut generated: Vec<String> = Vec::new();
    for (at, package) in packages.iter().enumerate() {
        let mut others: Vec<&v2::Package> = packages
            .iter()
            .enumerate()
            .filter(|(other, _)| *other != at)
            .map(|(_, other)| other)
            .collect();
        others.push(&std_ir);
        ridl_backend_rust::generate_pipeline(package, &[], false, &others).unwrap_or_else(
            |error| {
                panic!(
                    "evals/corpus/ros2: `{}` generates with no encoding: {}",
                    package.name, error.message
                )
            },
        );
        match ridl_backend_rust::generate_pipeline(
            package,
            &[ridl_backend_rust::WireEncoding::Proto3],
            false,
            &others,
        ) {
            Ok(_) => generated.push(package.name.clone()),
            Err(error) => {
                // The first declaration without a bound, in model order, is
                // named: `RosString` itself, or a struct that reaches it.
                assert!(
                    error.message.starts_with(&format!("`{}.", package.name))
                        && error.message.contains("` has no proto3 codec: ")
                        && error.message.contains("(NoBound)"),
                    "evals/corpus/ros2: `{}` is refused for a missing bound, got: {}",
                    package.name,
                    error.message
                );
                refused.insert(package.name.clone(), error.message);
            }
        }
    }
    assert_eq!(generated, ["builtininterfaces"]);
    for name in ["stdmsgs", "stdsrvs"] {
        assert!(
            refused[name].starts_with(&format!("`{name}.RosString` has no proto3 codec: ")),
            "`{name}`'s refusal names `RosString`, got: {}",
            refused[name]
        );
    }
    for name in [
        "stdmsgs",
        "stdsrvs",
        "geometrymsgs",
        "sensormsgs",
        "navmsgs",
        "nav2msgs",
    ] {
        assert!(
            refused.contains_key(name),
            "`{name}` is refused: {refused:?}"
        );
    }
}

