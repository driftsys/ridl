/// The bits of every member of `WideFlags`, which is width u64 because bit
/// 63 is a member, as the `u64` the wire carries.
const WIDE_FLAGS_ALL_U64: u64 = 1 | (1 << 32) | (1 << 63);

/// The prelude's `WIDEST_LABEL`, on this side.
fn widest_label() -> String {
    "\u{10348}".repeat(16)
}

/// A value `prost` holds, encodes and decodes: the oracle's side of a
/// [`Row`]. `Debug` text is what a decoded value is compared as, because
/// `prost`'s structs do not all implement `Eq`, and `NaN` reads as `NaN`.
trait Oracle {
    fn encode(&self) -> Vec<u8>;
    fn debug(&self) -> String;
    fn decode_debug(&self, bytes: &[u8]) -> Result<String, String>;
}

impl<T: prost::Message + Default + std::fmt::Debug> Oracle for T {
    fn encode(&self) -> Vec<u8> {
        prost::Message::encode_to_vec(self)
    }

    fn debug(&self) -> String {
        format!("{self:?}")
    }

    fn decode_debug(&self, bytes: &[u8]) -> Result<String, String> {
        T::decode(bytes)
            .map(|value| format!("{value:?}"))
            .map_err(|error| error.to_string())
    }
}

/// One value of the table, in both vocabularies: the expression the program
/// encodes under `encode-named`, and the `prost` value.
struct Row {
    message: &'static str,
    name: &'static str,
    ours: &'static str,
    prost: Box<dyn Oracle>,
    /// What `verify` answers for `prost`'s bytes: `ok` for a legal value,
    /// or the `Debug` text of the refusal where this codec is stricter than
    /// `prost` — a value outside a typl constraint that `prost` carries
    /// without checking.
    verdict: &'static str,
}

fn row<T: Oracle + 'static>(
    message: &'static str,
    name: &'static str,
    ours: &'static str,
    prost: T,
) -> Row {
    Row {
        message,
        name,
        ours,
        prost: Box::new(prost),
        verdict: "ok",
    }
}

/// A [`row`] whose value this codec refuses on `verify` with `verdict`.
fn refused_row<T: Oracle + 'static>(
    message: &'static str,
    name: &'static str,
    ours: &'static str,
    prost: T,
    verdict: &'static str,
) -> Row {
    Row {
        verdict,
        ..row(message, name, ours, prost)
    }
}

