//! The lowered codegen model — the artifact a codegen backend reads instead
//! of the raw IR (ADR-0020 decisions 8 and 9).
//!
//! The model carries, once and resolved, every fact the four in-tree backends
//! re-derive from `ridl.ir.v2` for themselves today: the scalar classes, the
//! pinned name transforms and the two compositions of them the wire backends
//! make, the resolution of every type reference over the packages the
//! lowering was handed, the transitive typl rules (the init of typl §5.8 and
//! the closure `derives.rs` walks), the tombstones in their slots, the
//! FlatBuffers projection whole, the interaction facts the descriptors and
//! the frame need, and the narrow contract-clause translation. The design
//! note is `docs/wip/2026-09-22-codegen-model-design.md`.
//!
//! **The home is this crate** (that note's D-11): the model is the projection
//! facts generalized — it carries what [`crate::name`] produces and what
//! [`crate::projection`] produces and adds the resolution and the typl rules
//! the backends still derive — and `ridl-ir` is the crate every consumer of
//! the model already depends on, so no edge in the dependency graph moves and
//! ADR-0020 decision 9 holds as it does today. The module moves to a crate of
//! its own if the lowering ever needs a dependency this crate must not carry
//! under `--no-default-features` on `wasm32`, or if a consumer needs the
//! model's types without the IR's; the `.proto` file and the package name do
//! not change with that move, so a plugin notices nothing.
//!
//! The canonical encoding is canonical protobuf JSON, in the dialect ADR-0014
//! decision 14 fixes for the IR and through the same generated impls and the
//! same reader guards ([`to_json_pretty`], [`from_json`]). Binary and
//! prototext are derived, as they are for the IR.
//!
//! The backend contract over the model — [`Backend`], the request and
//! response messages of `proto/ridl/codegen/v1/plugin.proto`, their JSON on
//! the pipe, and the path rule every host applies — is the `contract`
//! submodule (ADR-0020 decision 9; `docs/design/codegen-plugins.md`).

