/// The error [`to_json_pretty`] and [`to_text_format`] return, on the two
/// paths [`crate::v2::SerializeError`] has and for the same causes — the
/// model is written in the same dialect, through the same machinery.
#[derive(Debug)]
pub enum SerializeError {
    /// Canonical protobuf JSON: the one error path the pbjson-generated
    /// `Serialize` impl has is an `i32` enum field holding a discriminant
    /// outside the schema.
    Json(serde_json::Error),
    /// Prototext: the transcode into the dynamic message goes through the
    /// wire encoding, whose decoder enforces prost's fixed recursion limit.
    Text(prost::DecodeError),
}

impl std::fmt::Display for SerializeError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Json(source) => write!(
                f,
                "cannot render the codegen model as canonical protobuf JSON: {source}; the known \
                 cause is an enum field holding a discriminant outside the schema"
            ),
            Self::Text(source) => write!(
                f,
                "cannot render the codegen model as prototext: {source}; the known cause is \
                 composite nesting deeper than the transcoding decoder's recursion limit"
            ),
        }
    }
}

impl SerializeError {
    /// The IR's error, re-labelled as the model's: the model and the request
    /// are written through the IR's own machinery, so the causes are the
    /// same two.
    fn from_v2(error: crate::v2::SerializeError) -> Self {
        match error {
            crate::v2::SerializeError::Json(source) => Self::Json(source),
            crate::v2::SerializeError::Text(source) => Self::Text(source),
        }
    }
}

impl std::error::Error for SerializeError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Json(source) => Some(source),
            Self::Text(source) => Some(source),
        }
    }
}

/// Renders a lowered model as pretty-printed canonical protobuf JSON — the
/// `--emit codegen-model` artifact and the payload the codegen request
/// carries, byte for byte.
pub fn to_json_pretty(model: &v1::Model) -> Result<String, SerializeError> {
    render_json(model).map_err(SerializeError::from_v2)
}

/// Reads a lowered model from canonical protobuf JSON — the inverse of
/// [`to_json_pretty`], under the guards [`crate::v2::from_json`] states: the
/// input's nesting is measured first and refused past the same ceiling, and
/// the parse runs on the same explicitly sized stack.
///
/// The bound a reader of this schema must provision is 264 JSON levels, from
/// the map shape at the front end's own type-depth limit (design note §6.2),
/// so the ceiling of 1,000 leaves a factor of 3.8.
pub fn from_json(text: &str) -> Result<v1::Model, serde_json::Error> {
    read_json(text)
}

/// The nesting ceiling [`from_json`] enforces, in JSON bracket levels — the
/// IR's, because the two encodings are one dialect with one reader.
pub const MAX_JSON_NESTING_LEVELS: usize = MAX_JSON_NESTING;

/// Renders a lowered model in the protobuf text format — the inspection
/// encoding, derived from the same descriptor pool the IR's prototext uses.
pub fn to_text_format(model: &v1::Model) -> Result<String, SerializeError> {
    crate::v2::render_text_for(crate::v2::codegen_model_descriptor(), model)
        .map_err(SerializeError::from_v2)
}

/// Encodes a lowered model in the protobuf binary wire format — the derived
/// compact encoding, whose reader stops 100 message levels below the root.
pub fn to_binary(model: &v1::Model) -> Vec<u8> {
    prost::Message::encode_to_vec(model)
}

/// Decodes a lowered model from the protobuf binary wire format.
pub fn from_binary(bytes: &[u8]) -> Result<v1::Model, prost::DecodeError> {
    prost::Message::decode(bytes)
}

